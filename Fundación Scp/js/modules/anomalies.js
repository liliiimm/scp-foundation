const ANOMALY_STORAGE_KEY = "scp_foundation_anomaly_edits";

function anomalyEscape(value) {
    return String(value ?? "").replace(/[&<>"']/g, character => ({
        "&": "&amp;",
        "<": "&lt;",
        ">": "&gt;",
        '"': "&quot;",
        "'": "&#039;"
    })[character]);
}
/* INTERNAL ANOMALY NOTES */

const ANOMALY_NOTES_KEY = "scp_foundation_anomaly_notes";

function anomalyLoadNotes() {
    try {
        return JSON.parse(localStorage.getItem(ANOMALY_NOTES_KEY)) || {};
    } catch (error) {
        console.error("Error loading anomaly notes:", error);
        return {};
    }
}

function anomalySaveNotes(notes) {
    localStorage.setItem(ANOMALY_NOTES_KEY, JSON.stringify(notes));
}

function anomalyGetStaffTitle(character) {
    const name = character.name || character.fullName || "Unknown User";
    const role = String(character.type || character.role || "").toLowerCase();

    if (role.includes("security") || role.includes("guard")) {
        return `SECURITY PERSONNEL // ${name}`;
    }

    if (role.includes("elite")) {
        return `ELITE RESEARCHER // DR. ${name}`;
    }

    if (role.includes("chief")) {
        return `CHIEF RESEARCHER // DR. ${name}`;
    }

    if (role.includes("scientist")) {
        return `DR. ${name}`;
    }

    return `FOUNDATION PERSONNEL // ${name}`;
}
function anomalyFormatText(value) {
    return anomalyEscape(value)
        .replace(/\[\[REDACTED\]\]/g,
            '<span class="anomaly-redaction" aria-label="Classified information"></span>')
        .replace(/\n/g, "<br>");
}

function anomalyLoadDatabase() {
    let saved = {};

    try {
        saved = JSON.parse(localStorage.getItem(ANOMALY_STORAGE_KEY) || "{}");
    } catch (error) {
        console.error("Could not load anomaly records:", error);
    }

    return anomalyDatabase.map(original => {
        const changes = saved[original.designation];

        if (!changes) return structuredClone(original);

        return {
            ...structuredClone(original),
            ...changes,
            sections: changes.sections || structuredClone(original.sections)
        };
    });
}


/* =========================================================
   PERMISSIONS
========================================================= */

function anomalyCanEdit(character) {
    return Boolean(
        character &&
        ["scientist", "eliteScientist", "forensic"].includes(character.type) &&
        Number(character.clearance) >= 2
    );
}


/* =========================================================
   DATABASE RENDERER
========================================================= */

window.renderAnomalyDatabase = function(content, character) {

    let records = anomalyLoadDatabase();

    content.innerHTML = `
        <section class="anomaly-database">

            <header class="anomaly-database-header">
                <div>
                    <p class="anomaly-overline">
                        SCP FOUNDATION // CLASSIFIED DATABASE
                    </p>
                    <h2>ANOMALY DATABASE</h2>
                    <p>Central registry of contained anomalous entities.</p>
                </div>
                <span class="anomaly-stamp">CLASSIFIED</span>
            </header>

            <div class="anomaly-toolbar">
                <input
                    type="search"
                    id="anomalySearch"
                    placeholder="SEARCH BY DESIGNATION..."
                >
                <span id="anomalyCount"></span>
            </div>

            <div id="anomalyCards" class="anomaly-cards"></div>
            <div id="anomalyDossier" hidden></div>

        </section>
    `;

    const cards = content.querySelector("#anomalyCards");
    const search = content.querySelector("#anomalySearch");
    const count = content.querySelector("#anomalyCount");
    const dossier = content.querySelector("#anomalyDossier");

    function refreshRecords() {
        records = anomalyLoadDatabase();
    }

    function drawCards(term = "") {

        const filtered = records.filter(record => {
            const searchable = [
                record.designation,
                record.classification,
                record.status
            ].join(" ").toLowerCase();

            return searchable.includes(term.toLowerCase());
        });

        count.textContent = `${filtered.length} REGISTERED ENTITIES`;

        if (!filtered.length) {
            cards.innerHTML = `
                <div class="anomaly-empty">
                    <h3>NO MATCHING RECORDS</h3>
                    <p>No registered entity matches your search.</p>
                </div>
            `;
            return;
        }

        cards.innerHTML = filtered.map(record => `
            <article class="anomaly-database-card">

                <div class="anomaly-image-frame">
                    <img
                        src="${anomalyEscape(record.photo)}"
                        alt="${anomalyEscape(record.designation)}"
                        onerror="this.style.display='none'; this.parentElement.classList.add('image-missing');"
                    >
                    <span>SUBJECT IMAGE</span>
                </div>

                <div class="anomaly-card-information">
                    <p class="anomaly-designation">
                        ${anomalyEscape(record.designation)}
                    </p>

                    <h3>${anomalyEscape(record.name)}</h3>

                    <p class="anomaly-classification">
                        ${anomalyEscape(record.classification)}
                    </p>

                    <p class="anomaly-status">
                        STATUS: ${anomalyEscape(record.status)}
                    </p>

                    <button
                        type="button"
                        class="anomaly-open-button"
                        data-designation="${anomalyEscape(record.designation)}"
                    >
                        OPEN DOSSIER →
                    </button>
                </div>

            </article>
        `).join("");

        cards.querySelectorAll(".anomaly-open-button").forEach(button => {

            button.onclick = function() {

                const designation = this.getAttribute("data-designation");

                const selected = records.find(
                    record => record.designation === designation
                );

                if (!selected) {
                    console.error("SCP record not found:", designation);
                    return;
                }

                openDossier(selected);

            };

        });
    }

    drawCards();

    /* =====================================================
       DOSSIER VIEW
    ===================================================== */

    function openDossier(record) {

        cards.hidden = true;
        search.hidden = true;
        count.hidden = true;
        dossier.hidden = false;

        const editButton = anomalyCanEdit(character)
            ? `<button type="button" id="anomalyEdit">EDIT RECORD</button>`
            : "";

        /* STAFF IDENTITY */

        const staffRole = String(
            character.type || character.role || character.department || ""
        ).toLowerCase();

        const staffName = character.name ||
            character.fullName ||
            character.alias ||
            character.username ||
            "Unknown User";

        const isSecurity = /security|guard|seguridad/.test(staffRole);
        const isScientist = /scientist|research|cient[ií]fic|forensic|elite/.test(staffRole);

        const canWriteNotes = isSecurity || isScientist;

        let staffTitle = "FOUNDATION PERSONNEL";

        if (isSecurity && /chief|head|jefe/.test(staffRole)) {
            staffTitle = "CHIEF OF SECURITY";
        } else if (isSecurity) {
            staffTitle = "SECURITY PERSONNEL";
        } else if (/chief|head|jefe/.test(staffRole)) {
            staffTitle = "CHIEF RESEARCHER";
        } else if (/elite/.test(staffRole)) {
            staffTitle = "ELITE RESEARCHER";
        } else if (isScientist) {
            staffTitle = "DR.";
        }

        const staffIdentity = `${staffTitle} // ${staffName}`;

        const staffId = String(
            character.id || character.username || character.name || character.fullName || staffName
        );

        /* LOAD NOTES FOR THIS SCP */

        const allNotes = anomalyLoadNotes();
        const recordNotes = allNotes[record.designation] || [];

        const notesHTML = recordNotes.map((note, index) => `
        <article class="anomaly-note">

            <div class="anomaly-note-header">
                <strong>${anomalyEscape(note.author)}</strong>

                <span>${anomalyEscape(note.date)}</span>
            </div>

            <p>${anomalyEscape(note.text)}</p>

            ${
            note.authorId === staffId
                ? `<button
                            type="button"
                            class="anomaly-delete-note"
                            data-note-index="${index}">
                            DELETE NOTE
                       </button>`
                : ""
        }

        </article>
    `).join("");

        dossier.innerHTML = `
        <article class="anomaly-dossier">

            <div class="anomaly-dossier-top">
                <button type="button" id="anomalyBack">
                    ← RETURN TO DATABASE
                </button>

                <span>AUTHORIZED ACCESS // LEVEL ${anomalyEscape(character.clearance)}</span>
            </div>

            <header class="anomaly-dossier-heading">
                <div>
                    <p class="anomaly-overline">
                        SPECIAL CONTAINMENT PROCEDURES
                    </p>
                    <h2>${anomalyEscape(record.designation)}</h2>
                    <h3>${anomalyEscape(record.name)}</h3>
                </div>

                <span class="anomaly-dossier-class">
                    ${anomalyEscape(record.classification)}
                </span>
            </header>

            <div class="anomaly-dossier-profile">

                <div class="anomaly-dossier-image">
                    <img
                        src="${anomalyEscape(record.photo)}"
                        alt="${anomalyEscape(record.designation)}"
                        onerror="this.style.display='none'; this.parentElement.classList.add('image-missing');"
                    >
                </div>

                <div class="anomaly-dossier-data">
                    <div>
                        <span>DESIGNATION</span>
                        <strong>${anomalyEscape(record.designation)}</strong>
                    </div>
                    <div>
                        <span>OBJECT CLASS</span>
                        <strong>${anomalyEscape(record.classification)}</strong>
                    </div>
                    <div>
                        <span>THREAT LEVEL</span>
                        <strong>${anomalyEscape(record.threat)}</strong>
                    </div>
                    <div>
                        <span>CONTAINMENT STATUS</span>
                        <strong>${anomalyEscape(record.status)}</strong>
                    </div>
                    <div>
                        <span>DEPARTMENT</span>
                        <strong>${anomalyEscape(record.department)}</strong>
                    </div>
                </div>

            </div>

            <div class="anomaly-dossier-sections">
                ${record.sections.map(section => `
                    <section>
                        <h3>${anomalyEscape(section.title)}</h3>
                        <p>${anomalyFormatText(section.text)}</p>
                    </section>
                `).join("")}
            </div>

            <!-- INTERNAL STAFF NOTES -->

            <section class="anomaly-notes-section">

                <header class="anomaly-notes-heading">
                    <div>
                        <p class="anomaly-overline">CLASSIFIED COMMUNICATIONS</p>
                        <h3>INTERNAL STAFF NOTES</h3>
                    </div>

                    <span>${recordNotes.length} ENTRIES</span>
                </header>

                <div class="anomaly-notes-list">
                    ${
            notesHTML ||
            `<p class="anomaly-notes-empty">
                            NO INTERNAL NOTES RECORDED.
                        </p>`
        }
                </div>

                ${
            canWriteNotes
                ? `
                            <form id="anomalyNoteForm" class="anomaly-note-form">

                                <label>AUTHOR: ${anomalyEscape(staffIdentity)}</label>

                                <textarea
                                    id="anomalyNoteInput"
                                    placeholder="Write your observation..."
                                    maxlength="2000"
                                    required
                                ></textarea>

                                <button type="submit">
                                    SUBMIT INTERNAL NOTE
                                </button>

                            </form>
                        `
                : `
                            <p class="anomaly-notes-restricted">
                                INSUFFICIENT PERSONNEL CLEARANCE TO ADD NOTES.
                            </p>
                        `
        }

            </section>

            <div class="anomaly-editor-entry">
                ${editButton}
            </div>

            <footer class="anomaly-dossier-footer">
                SCP FOUNDATION // END OF AVAILABLE RECORD
            </footer>

        </article>
    `;

        /* RETURN TO DATABASE */

        dossier.querySelector("#anomalyBack").addEventListener("click", () => {
            dossier.hidden = true;
            cards.hidden = false;
            search.hidden = false;
            count.hidden = false;
            refreshRecords();
            drawCards(search.value);
        });

        /* EDIT RECORD */

        const edit = dossier.querySelector("#anomalyEdit");

        if (edit) {
            edit.addEventListener("click", () => openEditor(record));
        }

        /* SUBMIT NOTE */

        const noteForm = dossier.querySelector("#anomalyNoteForm");

        if (noteForm) {
            noteForm.addEventListener("submit", function(event) {
                event.preventDefault();

                const input = dossier.querySelector("#anomalyNoteInput");
                const noteText = input.value.trim();

                if (!noteText) return;

                const notes = anomalyLoadNotes();

                if (!notes[record.designation]) {
                    notes[record.designation] = [];
                }

                notes[record.designation].push({
                    author: staffIdentity,
                    authorId: staffId,
                    text: noteText,
                    date: new Date().toLocaleString()
                });

                anomalySaveNotes(notes);

                openDossier(record);
            });
        }

        /* DELETE OWN NOTES */

        dossier.querySelectorAll(".anomaly-delete-note").forEach(button => {
            button.addEventListener("click", function() {

                const index = Number(this.dataset.noteIndex);
                const notes = anomalyLoadNotes();

                if (!notes[record.designation]) return;

                const selectedNote = notes[record.designation][index];

                if (!selectedNote || selectedNote.authorId !== staffId) return;

                if (!confirm("DELETE THIS INTERNAL NOTE?")) return;

                notes[record.designation].splice(index, 1);

                anomalySaveNotes(notes);

                openDossier(record);
            });
        });

    }
    /* =====================================================
       SCIENTIFIC EDITOR
    ===================================================== */

    function openEditor(record) {

        if (!anomalyCanEdit(character)) return;

        dossier.innerHTML = `
            <article class="anomaly-editor">

                <div class="anomaly-dossier-top">
                    <button type="button" id="editorCancel">
                        ← CANCEL
                    </button>
                    <span>SCIENTIFIC DATABASE // EDIT MODE</span>
                </div>

                <header>
                    <p class="anomaly-overline">AUTHORIZED PERSONNEL ONLY</p>
                    <h2>EDIT ${anomalyEscape(record.designation)}</h2>
                    <p>Changes will be saved to this browser.</p>
                </header>

                <form id="anomalyEditForm">

                    <div class="anomaly-editor-grid">

                        <label>
                            Designation
                            <input name="designation" value="${anomalyEscape(record.designation)}" disabled>
                        </label>

                        <label>
                            Classification
                            <input name="classification" value="${anomalyEscape(record.classification)}" required>
                        </label>

                        <label>
                            Threat level
                            <input name="threat" value="${anomalyEscape(record.threat)}">
                        </label>

                        <label>
                            Containment status
                            <input name="status" value="${anomalyEscape(record.status)}">
                        </label>

                        <label>
                            Department
                            <input name="department" value="${anomalyEscape(record.department)}">
                        </label>

                        <label>
                            Image path
                            <input name="photo" value="${anomalyEscape(record.photo)}">
                        </label>

                    </div>

                    <div class="anomaly-editor-sections">
                        ${record.sections.map((section, index) => `
                            <label class="anomaly-editor-section">
                                ${anomalyEscape(section.title)}
                                <textarea
                                    name="section-${index}"
                                    rows="8"
                                >${anomalyEscape(section.text)}</textarea>
                            </label>
                        `).join("")}
                    </div>

                    <div class="anomaly-editor-actions">
                        <button type="button" id="editorCancelBottom">
                            CANCEL
                        </button>
                        <button type="submit">
                            SAVE CHANGES
                        </button>
                    </div>

                </form>

            </article>
        `;

        const form = dossier.querySelector("#anomalyEditForm");

        function cancelEditor() {
            openDossier(record);
        }

        dossier.querySelector("#editorCancel").addEventListener("click", cancelEditor);
        dossier.querySelector("#editorCancelBottom").addEventListener("click", cancelEditor);

        form.addEventListener("submit", event => {

            event.preventDefault();

            if (!anomalyCanEdit(character)) return;

            const formData = new FormData(form);
            const updated = {
                classification: formData.get("classification"),
                threat: formData.get("threat"),
                status: formData.get("status"),
                department: formData.get("department"),
                photo: formData.get("photo"),
                sections: record.sections.map((section, index) => ({
                    title: section.title,
                    text: formData.get(`section-${index}`)
                }))
            };

            let saved = {};

            try {
                saved = JSON.parse(
                    localStorage.getItem(ANOMALY_STORAGE_KEY) || "{}"
                );
            } catch (error) {
                console.error("Could not read saved records:", error);
            }

            saved[record.designation] = updated;

            try {
                localStorage.setItem(
                    ANOMALY_STORAGE_KEY,
                    JSON.stringify(saved)
                );

                refreshRecords();

                const updatedRecord = records.find(
                    item => item.designation === record.designation
                );

                if (updatedRecord) {
                    openDossier(updatedRecord);
                }

            } catch (error) {
                alert("ERROR: Changes could not be saved in this browser.");
                console.error(error);
            }

        });
    }


    /* =====================================================
       SEARCH
    ===================================================== */

    search.addEventListener("input", function() {
        dossier.hidden = true;
        cards.hidden = false;
        drawCards(search.value);
    });
};
